
-- Create Database
CREATE DATABASE IF NOT EXISTS multi_sport_selection;
USE multi_sport_selection;

-- ==========================================
-- CORE TABLES
-- ==========================================

CREATE TABLE IF NOT EXISTS SPORT (
    sport_id INT AUTO_INCREMENT PRIMARY KEY,
    sport_name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS TEAM (
    team_id INT AUTO_INCREMENT PRIMARY KEY,
    sport_id INT,
    team_name VARCHAR(100) NOT NULL,
    FOREIGN KEY (sport_id) REFERENCES SPORT(sport_id)
);

CREATE TABLE IF NOT EXISTS PLAYER (
    player_id INT AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    age INT NOT NULL,
    team_id INT,
    FOREIGN KEY (team_id) REFERENCES TEAM(team_id)
);

CREATE TABLE IF NOT EXISTS MATCH_DETAILS (
    match_id INT AUTO_INCREMENT PRIMARY KEY,
    sport_id INT,
    match_date DATE NOT NULL,
    event_name VARCHAR(150) NOT NULL,
    FOREIGN KEY (sport_id) REFERENCES SPORT(sport_id)
);

CREATE TABLE IF NOT EXISTS FITNESS_RECORD (
    record_id INT AUTO_INCREMENT PRIMARY KEY,
    player_id INT,
    stamina_score INT NOT NULL,
    speed_score INT NOT NULL,
    injury_status BOOLEAN NOT NULL DEFAULT FALSE,
    test_date DATE NOT NULL,
    FOREIGN KEY (player_id) REFERENCES PLAYER(player_id)
);

CREATE TABLE IF NOT EXISTS SELECTION (
    player_id INT,
    match_id INT,
    selection_status ENUM('Selected', 'Not Selected', 'Pending') DEFAULT 'Pending',
    PRIMARY KEY (player_id, match_id),
    FOREIGN KEY (player_id) REFERENCES PLAYER(player_id),
    FOREIGN KEY (match_id) REFERENCES MATCH_DETAILS(match_id)
);

-- ==========================================
-- SPORT-SPECIFIC PERFORMANCE TABLES
-- ==========================================

CREATE TABLE IF NOT EXISTS STATS_CRICKET (
    player_id INT, match_id INT, runs_scored INT DEFAULT 0, wickets_taken INT DEFAULT 0, catches INT DEFAULT 0, balls_faced INT DEFAULT 0,
    PRIMARY KEY (player_id, match_id), FOREIGN KEY (player_id) REFERENCES PLAYER(player_id), FOREIGN KEY (match_id) REFERENCES MATCH_DETAILS(match_id)
);

CREATE TABLE IF NOT EXISTS STATS_FOOTBALL (
    player_id INT, match_id INT, goals INT DEFAULT 0, assists INT DEFAULT 0, yellow_cards INT DEFAULT 0, red_cards INT DEFAULT 0, minutes_played INT DEFAULT 0,
    PRIMARY KEY (player_id, match_id), FOREIGN KEY (player_id) REFERENCES PLAYER(player_id), FOREIGN KEY (match_id) REFERENCES MATCH_DETAILS(match_id)
);

CREATE TABLE IF NOT EXISTS STATS_BADMINTON (
    player_id INT, match_id INT, sets_won INT DEFAULT 0, sets_lost INT DEFAULT 0, total_points_won INT DEFAULT 0,
    PRIMARY KEY (player_id, match_id), FOREIGN KEY (player_id) REFERENCES PLAYER(player_id), FOREIGN KEY (match_id) REFERENCES MATCH_DETAILS(match_id)
);

CREATE TABLE IF NOT EXISTS STATS_TENNIS (
    player_id INT, match_id INT, sets_won INT DEFAULT 0, aces INT DEFAULT 0, double_faults INT DEFAULT 0, unforced_errors INT DEFAULT 0,
    PRIMARY KEY (player_id, match_id), FOREIGN KEY (player_id) REFERENCES PLAYER(player_id), FOREIGN KEY (match_id) REFERENCES MATCH_DETAILS(match_id)
);

CREATE TABLE IF NOT EXISTS STATS_BASKETBALL (
    player_id INT, match_id INT, points INT DEFAULT 0, rebounds INT DEFAULT 0, assists INT DEFAULT 0, steals INT DEFAULT 0, blocks INT DEFAULT 0,
    PRIMARY KEY (player_id, match_id), FOREIGN KEY (player_id) REFERENCES PLAYER(player_id), FOREIGN KEY (match_id) REFERENCES MATCH_DETAILS(match_id)
);

CREATE TABLE IF NOT EXISTS STATS_F1 (
    player_id INT, match_id INT, grid_position INT, finish_position INT, fastest_lap BOOLEAN DEFAULT FALSE, points_earned INT DEFAULT 0,
    PRIMARY KEY (player_id, match_id), FOREIGN KEY (player_id) REFERENCES PLAYER(player_id), FOREIGN KEY (match_id) REFERENCES MATCH_DETAILS(match_id)
);

CREATE TABLE IF NOT EXISTS STATS_MOTOGP (
    player_id INT, match_id INT, grid_position INT, finish_position INT, crashes INT DEFAULT 0, points_earned INT DEFAULT 0,
    PRIMARY KEY (player_id, match_id), FOREIGN KEY (player_id) REFERENCES PLAYER(player_id), FOREIGN KEY (match_id) REFERENCES MATCH_DETAILS(match_id)
);

CREATE TABLE IF NOT EXISTS STATS_HOCKEY (
    player_id INT, match_id INT, goals INT DEFAULT 0, assists INT DEFAULT 0, penalty_minutes INT DEFAULT 0, shots_on_goal INT DEFAULT 0,
    PRIMARY KEY (player_id, match_id), FOREIGN KEY (player_id) REFERENCES PLAYER(player_id), FOREIGN KEY (match_id) REFERENCES MATCH_DETAILS(match_id)
);

CREATE TABLE IF NOT EXISTS STATS_SWIMMING (
    player_id INT, match_id INT, stroke_type VARCHAR(50), distance_meters INT, time_seconds DECIMAL(5,2), finish_position INT,
    PRIMARY KEY (player_id, match_id), FOREIGN KEY (player_id) REFERENCES PLAYER(player_id), FOREIGN KEY (match_id) REFERENCES MATCH_DETAILS(match_id)
);

